// Дженерики ПРОТИВ interface{}/any: когда что выбирать.
//
// До 1.18 «обобщённый» код писали на interface{} (с 1.18 — псевдоним `any`).
// Минусы такого подхода:
//   - теряется информация о типе → нужны приведения типов в рантайме;
//   - приведение может УПАСТЬ в рантайме (паника), компилятор не помогает;
//   - значения «упаковываются» (boxing), что иногда бьёт по производительности.
//
// Дженерики сохраняют конкретный тип и проверяются на этапе компиляции.
package main

import "fmt"

// Старый способ: any теряет тип, требует приведения и может паниковать.
func SumAny(s []any) int {
	total := 0
	for _, v := range s {
		// Если в срезе окажется не int — это паника в рантайме.
		total += v.(int)
	}
	return total
}

// Новый способ: тип известен компилятору, приведения не нужны.
func Sum[T int | float64](s []T) T {
	var total T
	for _, v := range s {
		total += v
	}
	return total
}

func main() {
	// any-версия работает, пока повезло с типами...
	fmt.Println("SumAny:", SumAny([]any{1, 2, 3}))

	// ...но вот такая ошибка НЕ ловится компилятором — упадёт в рантайме:
	//   SumAny([]any{1, "два", 3})   // panic: interface conversion
	// Раскомментируйте, чтобы увидеть панику.

	// Дженерик-версия: ошибку типов поймает КОМПИЛЯТОР.
	fmt.Println("Sum(int):", Sum([]int{1, 2, 3}))
	fmt.Println("Sum(float64):", Sum([]float64{1.5, 2.5}))
	//   Sum([]string{"a"})   // ошибка компиляции, до запуска

	fmt.Println()
	fmt.Println("Вывод:")
	fmt.Println("- any: когда тип действительно произвольный и неважен")
	fmt.Println("       (напр. fmt.Println, хранение разнородных данных);")
	fmt.Println("- дженерики: когда одна логика для многих типов,")
	fmt.Println("       и нужна типобезопасность на этапе компиляции.")
}
