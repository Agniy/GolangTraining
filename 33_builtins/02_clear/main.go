// Встроенная функция clear (Go 1.21).
//
// clear очищает map или срез. Поведение зависит от того, что передали:
//
//   - map   — УДАЛЯЕТ все пары. После clear len(m) == 0. Это удобнее, чем
//     цикл `for k := range m { delete(m, k) }`, и быстрее.
//   - срез  — обнуляет все элементы (ставит нулевое значение типа), но
//     ДЛИНУ НЕ МЕНЯЕТ. len(s) остаётся прежним, элементы становятся 0/""/nil.
//
// Зачем clear для срезов: например, чтобы переиспользовать буфер, убрав ссылки
// на старые объекты (помочь сборщику мусора), не меняя длину.
package main

import "fmt"

func main() {
	// --- clear для map: удаляет все пары ---
	m := map[string]int{"a": 1, "b": 2, "c": 3}
	fmt.Println("map до clear:", len(m), m) // 3 map[a:1 b:2 c:3]
	clear(m)
	fmt.Println("map после clear:", len(m), m) // 0 map[]

	// --- clear для среза: обнуляет элементы, длину НЕ меняет ---
	s := []int{1, 2, 3, 4, 5}
	fmt.Println("срез до clear:", len(s), s) // 5 [1 2 3 4 5]
	clear(s)
	fmt.Println("срез после clear:", len(s), s) // 5 [0 0 0 0 0]

	// --- Разница с map: длина сохраняется ---
	// Чтобы «опустошить» срез по-настоящему, используют s = s[:0].
	s2 := []string{"x", "y", "z"}
	clear(s2)
	fmt.Printf("срез строк после clear: %d %q\n", len(s2), s2) // 3 ["" "" ""]

	// --- clear особенно полезен для NaN-ключей в map ---
	// Ключи NaN нельзя удалить через delete (NaN != NaN), но clear убирает их.
	nan := map[float64]string{}
	nan[0.0] = "zero"
	// (в реальном коде NaN мог попасть как ключ из вычислений)
	clear(nan)
	fmt.Println("map после clear:", len(nan)) // 0
}
