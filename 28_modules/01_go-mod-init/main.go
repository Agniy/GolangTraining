// Минимальная программа внутри Go-модуля.
//
// До Go 1.11 код обязан был лежать внутри $GOPATH/src. Модули (Go 1.11, 2018)
// сняли это ограничение: теперь проект может находиться где угодно, а его
// границы и зависимости описывает файл go.mod.
//
// Запуск из этой папки:
//
//	go run .          // собрать и запустить весь пакет main
//	go build          // собрать бинарник example.com/hello (./hello или hello.exe)
//	go run main.go    // тоже сработает для одного файла
package main

import "fmt"

func main() {
	fmt.Println("Hello from a Go module!")
}
