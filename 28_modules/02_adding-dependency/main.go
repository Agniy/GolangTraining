// Использование внешней зависимости в модуле.
//
// Пакет rsc.io/quote — классический учебный пример из документации Go.
// Чтобы добавить зависимость, достаточно её импортировать и выполнить:
//
//	go mod tidy        // скачает пакет, добавит require в go.mod и хеши в go.sum
//
// или явно:
//
//	go get rsc.io/quote@v1.5.2
//
// go.sum хранит криптографические контрольные суммы зависимостей —
// это гарантирует, что у всех собирается ровно тот же код.
package main

import (
	"fmt"

	"rsc.io/quote"
)

func main() {
	fmt.Println(quote.Hello())
	fmt.Println(quote.Go())
}
