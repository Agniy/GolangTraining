package main

import (
	"fmt"
	"sync"
)

// wg — глобальный WaitGroup, который отслеживает, сколько горутин ещё работает.
// Используем глобальную переменную, чтобы foo и bar могли вызвать wg.Done() без передачи аргументов.
var wg sync.WaitGroup

// main запускает две горутины (foo и bar) параллельно и ждёт их завершения.
func main() {
	// Сообщаем WaitGroup, что нужно дождаться 2 горутин.
	// Важно вызвать Add() ДО запуска горутин, иначе Wait() может завершиться раньше времени.
	wg.Add(2)

	// Запускаем foo и bar как горутины — они работают одновременно.
	// Порядок их выполнения и вывода не гарантирован (зависит от планировщика Go).
	go foo()
	go bar()

	// Блокируем main до тех пор, пока обе горутины не вызовут wg.Done().
	// Без этого программа завершится сразу, не дождавшись горутин.
	wg.Wait()
}

// foo выводит числа от 0 до 44 с префиксом "Foo:".
func foo() {
	for i := 0; i < 45; i++ {
		fmt.Println("Foo:", i)
	}
	// Сигнализируем WaitGroup, что горутина завершила работу (счётчик уменьшается на 1).
	wg.Done()
}

// bar выводит числа от 0 до 44 с префиксом "Bar:".
func bar() {
	for i := 0; i < 45; i++ {
		fmt.Println("Bar:", i)
	}
	// Сигнализируем WaitGroup, что горутина завершила работу (счётчик уменьшается на 1).
	wg.Done()
}
